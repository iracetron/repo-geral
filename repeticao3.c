#include <stdio.h>

//Diferente dos outros comandos de repetição, o comando for tem a inicialização, condição de parada e atualização na mesma string
//Tudo que fazemos com for, conseguimos fazer com while.

int main(){

    int i;

    for(i = 1; i <= 10; i++){
        printf("%d.\n", i);
    }
    
}