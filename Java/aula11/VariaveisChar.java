public class VariaveisChar{

  public static void main(String[] args){

    char o = 'o';
    char i = 'i';

    System.out.println(o + i);
    System.out.println("" + o + i);

    char o2 = 111;
    char i2 = 105;
    char interrogacao = 0x3F;

    System.out.println("" + o2 + i2 + interrogacao);
    
  }
}